const header = "// Code generated by internal/gen from spec/openapi.json. DO NOT EDIT.\n\n"

// comment writes text as a // comment block.
func comment(b *bytes.Buffer, indent, text string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			fmt.Fprintf(b, "%s//\n", indent)
		} else {
			fmt.Fprintf(b, "%s// %s\n", indent, line)
		}
	}
}

/* ---------------------------------------------------------------- types -- */

func (g *generator) types() []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package verisec\n\n")
	for _, name := range g.order {
		g.emitType(&b, g.defs[name])
	}
	return b.Bytes()
}

func (g *generator) emitType(b *bytes.Buffer, def *typeDef) {
	comment(b, "", def.Doc)
	switch def.Kind {
	case defAlias:
		fmt.Fprintf(b, "type %s = %s\n\n", def.Name, def.Alias)
		return
	case defOpen:
		fmt.Fprintf(b, "type %s struct {\n\tOpenResult\n", def.Name)
		if def.Answer {
			b.WriteString("\n\t// LastResponse is the response the result came from: status, headers, request id, warnings and latency.\n")
			b.WriteString("\tLastResponse *ResponseInfo `json:\"-\"`\n")
		}
		b.WriteString("}\n\n")
		if def.Answer {
			fmt.Fprintf(b, "func (v *%s) setLastResponse(info *ResponseInfo) { v.LastResponse = info }\n\n", def.Name)
		}
		return
	}

	fmt.Fprintf(b, "type %s struct {\n", def.Name)
	for _, f := range def.Fields {
		comment(b, "\t", f.Doc)
		fmt.Fprintf(b, "\t%s %s `%s`\n", f.Name, f.Type, g.tag(def, f))
	}
	if def.Side == answer {
		b.WriteString("\n\t// Extra holds the members that have no field above, or whose JSON type differs from the spec.\n")
		b.WriteString("\tExtra map[string]any `json:\"-\"`\n")
		if def.Answer {
			b.WriteString("\n\t// LastResponse is the response the result came from: status, headers, request id, warnings and latency.\n")
			b.WriteString("\tLastResponse *ResponseInfo `json:\"-\"`\n")
		}
	}
	b.WriteString("}\n\n")

	if def.Side == answer {
		b.WriteString("// UnmarshalJSON reads the known members into their fields and keeps the others in Extra.\n")
		fmt.Fprintf(b, "func (v *%s) UnmarshalJSON(data []byte) error {\n\ttype plain %s\n\treturn decodeObject(data, (*plain)(v), &v.Extra)\n}\n\n", def.Name, def.Name)
		b.WriteString("// MarshalJSON writes the fields, then the members kept in Extra.\n")
		fmt.Fprintf(b, "func (v %s) MarshalJSON() ([]byte, error) {\n\ttype plain %s\n\treturn encodeObject(plain(v), v.Extra)\n}\n\n", def.Name, def.Name)
		if def.Answer {
			fmt.Fprintf(b, "func (v *%s) setLastResponse(info *ResponseInfo) { v.LastResponse = info }\n\n", def.Name)
		}
	}
}

// tag is a field's struct tag. Request fields leave out empty values, except
// the required numbers and booleans, where zero is a value; the client's
// encoder also sends an empty but non-nil slice as []. Image lists carry what
// the client fills in for their entries.
func (g *generator) tag(def *typeDef, f *fieldDef) string {
	omit := ",omitempty"
	if def.Side == request && f.Required && (f.Cat == catInt || f.Cat == catFloat || f.Cat == catBool) {
		omit = ""
	}
	tag := fmt.Sprintf("json:%q", f.Wire+omit)
	if f.List != nil {
		var parts []string
		if f.List.IndexKey != "" {
			parts = append(parts, "index="+f.List.IndexKey)
		}
		if f.List.IDKey != "" {
			parts = append(parts, "id="+f.List.IDKey)
		}
		parts = append(parts, "label="+f.List.ItemLabel)
		tag += fmt.Sprintf(" verisec:%q", "list,"+strings.Join(parts, ","))
	}
	return tag
}

/* ------------------------------------------------------------ resources -- */

// listAnd joins items as "a, b and c".
func listAnd(items []string) string {
	if len(items) < 2 {
		return strings.Join(items, "")
	}
	return strings.Join(items[:len(items)-1], ", ") + " and " + items[len(items)-1]
}

func (g *generator) tagGroups() map[string]string {
	groups := map[string]string{}
	for _, raw := range g.spec.Arr("x-tagGroups") {
		o, _ := raw.(*Object)
		for _, t := range o.Arr("tags") {
			if name, ok := t.(string); ok {
				groups[name] = o.Str("name")
			}
		}
	}
	return groups
}

func (s *service) doc() string {
	var methods []string
	for _, o := range s.Ops {
		methods = append(methods, o.Method)
	}
	for _, c := range s.Children {
		methods = append(methods, c.Field+" (a resource)")
	}
	return fmt.Sprintf("%s holds the %s APIs: %s.", s.Type, strings.Join(s.Segs, "."), listAnd(methods))
}

func (g *generator) resources() []byte {
	groups := g.tagGroups()
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package verisec\n\nimport (\n\t\"context\"\n\t\"net/http\"\n)\n\n")

	b.WriteString(`// Client calls the VeriSec API: identity (KYC) and Financial checks. Create one
// with New and share it: it is safe for concurrent use.
//
// Every API is a method, grouped as the API groups them (client.Face.Verify,
// client.Phone.Otp.Send, client.Cheques.MicrLine). Each method takes a context
// first and request options last, and returns the answer (for KYC, the
// envelope's data) with the response info in its LastResponse field:
//
//	result, err := client.Face.Verify(ctx, &verisec.FaceVerifyParams{
//		Image1: verisec.ImageFromPath("selfie.jpg"),
//		Image2: verisec.ImageFromPath("id-photo.jpg"),
//	})
type Client struct {
`)
	group := ""
	for _, s := range g.services {
		if name := groups[s.Tag]; name != "" && name != group {
			if group != "" {
				b.WriteString("\n")
			}
			fmt.Fprintf(&b, "\t// %s\n\n", name)
			group = name
		}
		comment(&b, "\t", s.Field+" "+strings.TrimPrefix(s.doc(), s.Type+" "))
		fmt.Fprintf(&b, "\t%s *%s\n", s.Field, s.Type)
	}
	b.WriteString("\n\tt *transport\n}\n\n")

	b.WriteString("func newClient(t *transport) *Client {\n\tc := &Client{t: t}\n")
	var attach func(prefix string, ss []*service)
	attach = func(prefix string, ss []*service) {
		for _, s := range ss {
			fmt.Fprintf(&b, "\t%s.%s = &%s{t: t}\n", prefix, s.Field, s.Type)
			attach(prefix+"."+s.Field, s.Children)
		}
	}
	attach("c", g.services)
	b.WriteString("\treturn c\n}\n\n")

	var emit func(ss []*service)
	emit = func(ss []*service) {
		for _, s := range ss {
			g.emitService(&b, s)
			emit(s.Children)
		}
	}
	emit(g.services)

	b.WriteString("// operations maps every operationId of the spec to the method that calls it.\nvar operations = map[string]string{\n")
	for _, o := range g.sortedOps() {
		fmt.Fprintf(&b, "\t%q: %q,\n", o.ID, pascalPath(o))
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func (g *generator) emitService(b *bytes.Buffer, s *service) {
	comment(b, "", s.doc())
	fmt.Fprintf(b, "type %s struct {\n", s.Type)
	for _, c := range s.Children {
		comment(b, "\t", c.Field+" "+strings.TrimPrefix(c.doc(), c.Type+" "))
		fmt.Fprintf(b, "\t%s *%s\n\n", c.Field, c.Type)
	}
	b.WriteString("\tt *transport\n}\n\n")
	for _, o := range s.Ops {
		g.emitMethod(b, s, o)
	}
}

// methodDoc is the summary, the first paragraph of the description and the price.
func methodDoc(o *operation) string {
	doc := fmt.Sprintf("%s calls %s: %s %s.", o.Method, o.Summary, o.HTTP, o.Path)
	if first, _, _ := strings.Cut(o.Description, "\n\n"); strings.TrimSpace(first) != "" {
		doc += "\n\n" + strings.TrimSpace(first)
	}
	if o.Price == "" || o.Price == "0" {
		doc += "\n\nFree: not charged."
	} else {
		doc += fmt.Sprintf("\n\nPrice: %s credits per successful call.", o.Price)
	}
	return doc
}

func (g *generator) emitMethod(b *bytes.Buffer, s *service, o *operation) {
	args := []string{"ctx context.Context"}
	var pathArgs []string
	for _, p := range o.PathParams {
		pathArgs = append(pathArgs, paramName(p))
		args = append(args, paramName(p)+" string")
	}
	if o.Params != "" {
		args = append(args, "params *"+o.Params)
	}
	args = append(args, "opts ...RequestOption")

	fields := []string{"method: http.Method" + upperFirst(strings.ToLower(o.HTTP))}
	if len(o.PathParams) > 0 {
		fields = append(fields, "path: path")
	} else {
		fields = append(fields, fmt.Sprintf("path: %q", o.Path))
	}
	switch o.Body {
	case "json":
		fields = append(fields, "body: params")
	case "multipart":
		fields = append(fields, "form: params")
	case "query":
		fields = append(fields, "query: params")
	}
	if o.Source {
		fields = append(fields, "source: true")
	}
	envelope := "envelopeObject"
	if o.Envelope == "data" {
		envelope = "envelopeData"
	}
	fields = append(fields, "envelope: "+envelope)

	comment(b, "", methodDoc(o))
	fmt.Fprintf(b, "func (s *%s) %s(%s) (*%s, error) {\n", s.Type, o.Method, strings.Join(args, ", "), o.Answer)
	if len(o.PathParams) > 0 {
		fmt.Fprintf(b, "\tpath, err := buildPath(%q, %s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", o.Path, strings.Join(pathArgs, ", "))
	}
	fmt.Fprintf(b, "\treturn doCall[%s](ctx, s.t, &call{%s}, opts)\n}\n\n", o.Answer, strings.Join(fields, ", "))
}
